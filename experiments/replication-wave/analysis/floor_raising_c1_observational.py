#!/usr/bin/env python3
"""C1 observational analog of the floor-raising test.

The label-swap floor-raising test (`floor_raising_test.py`) shows that
within-response per-label SELF uplift Δ correlates negatively with the
non-self baseline composite (Claude ρ=-0.673, Gemini ρ=-0.834). This is a
*causal* within-response test on the 20 paired label-swap responses.

This script tests the same floor-raising hypothesis on the C1 baseline data
(160 rows; all 4 judges including Kimi). The analog is:
- For each judge J and each prompt P, take the J-authored response.
- self_score = J's own composite for that response.
- baseline = mean of the other 3 judges' composites for that response.
- delta = self_score − baseline.
We then correlate delta with baseline per judge (10 prompts each).

If the floor-raising mechanism generalizes from the causal slice to the
observational data, we expect a negative correlation: judges should over-
reward their own outputs most strongly on outputs the other judges rate
relatively low. We also test the negative pattern: Kimi's strong self-
penalty (−2.87 in C1) means *negative* Δ — does Kimi self-penalize the most
on its weakest outputs (over-penalty interaction), or most on its strongest
outputs (excess humility)?

Outputs:
- results/floor_raising_c1_observational.csv:
  judge, prompt_id, self_score, baseline_mean, delta
- results/floor_raising_c1_observational.md: summary table per judge
"""
from __future__ import annotations
import csv, pathlib
import numpy as np
from collections import defaultdict

REPO = pathlib.Path(__file__).resolve().parents[3]
RW = REPO / "experiments" / "replication-wave"
OUT = RW / "results"

DIMS = ["correctness", "completeness", "clarity", "creativity", "constraint_adherence"]
JUDGES = ["claude-opus-4.7", "gemini-3.1-pro", "gpt-5.5", "kimi-k2.6"]
SHORT = {"claude-opus-4.7": "claude", "gemini-3.1-pro": "gemini", "gpt-5.5": "gpt", "kimi-k2.6": "kimi"}
RNG = np.random.default_rng(0xF1009)
B = 2000

rows = list(csv.DictReader(open(RW / "results" / "long_scores.csv")))
c1 = [r for r in rows if r["condition"] == "c1"]

def comp(r):
    return float(np.mean([float(r[d]) for d in DIMS]))

# (author, prompt) -> {judge: composite}
by_resp = defaultdict(dict)
for r in c1:
    by_resp[(r["author"], r["prompt_id"])][r["judge"]] = comp(r)

def ranks(x):
    n = len(x)
    o = sorted(range(n), key=lambda i: x[i])
    r = [0.0] * n
    i = 0
    while i < n:
        j = i
        while j + 1 < n and x[o[j + 1]] == x[o[i]]:
            j += 1
        avg = (i + j) / 2.0 + 1
        for k in range(i, j + 1):
            r[o[k]] = avg
        i = j + 1
    return r

def spearman(a, b):
    if len(a) < 2: return float("nan")
    ra, rb = ranks(a), ranks(b)
    if np.std(ra) == 0 or np.std(rb) == 0: return float("nan")
    return float(np.corrcoef(ra, rb)[0, 1])

def pearson(a, b):
    if len(a) < 2: return float("nan")
    a = np.asarray(a, dtype=float); b = np.asarray(b, dtype=float)
    if np.std(a) == 0 or np.std(b) == 0: return float("nan")
    return float(np.corrcoef(a, b)[0, 1])

def boot_ci(a, b, fn, B=2000):
    a = np.asarray(a, dtype=float); b = np.asarray(b, dtype=float)
    n = len(a)
    vals = []
    for _ in range(B):
        idx = RNG.integers(0, n, n)
        if np.std(a[idx]) == 0 or np.std(b[idx]) == 0:
            continue
        vals.append(fn(a[idx].tolist(), b[idx].tolist()))
    if not vals: return float("nan"), float("nan")
    return float(np.percentile(vals, 2.5)), float(np.percentile(vals, 97.5))

per_judge = {j: [] for j in JUDGES}
for (author, pid), jmap in by_resp.items():
    if author not in jmap: continue
    self_score = jmap[author]
    others = [v for j, v in jmap.items() if j != author]
    if len(others) < 2: continue
    baseline = float(np.mean(others))
    per_judge[author].append({
        "judge": author, "pid": pid, "self": self_score,
        "baseline": baseline, "delta": self_score - baseline,
    })

csv_p = OUT / "floor_raising_c1_observational.csv"
with csv_p.open("w", newline="") as f:
    w = csv.writer(f, lineterminator="\n")
    w.writerow(["judge", "prompt_id", "self_score", "baseline_mean", "delta"])
    for j in JUDGES:
        for p in per_judge[j]:
            w.writerow([SHORT[j], p["pid"], f"{p['self']:.3f}", f"{p['baseline']:.3f}", f"{p['delta']:.3f}"])

md = []
md.append("# C1 observational floor-raising test\n")
md.append("Generated by `analysis/floor_raising_c1_observational.py`. C1 (baseline blinded) observational analog of the label-swap floor-raising test in `floor_raising_test.md`. For each judge J and each of the 10 prompts P, we form the J-authored response; record J's own composite (`self_score`); record the mean of the other three judges' composites for the same response (`baseline_mean`); and form `delta = self_score − baseline_mean`. The same negative-correlation pattern (judges over-reward their own outputs most strongly on outputs other judges rate weakest) would predict ρ(Δ, baseline) < 0.\n")
md.append("\n## Summary\n")
md.append("| Judge | n | mean Δ | Pearson r(Δ, base) | Spearman ρ | 95% CI on ρ |")
md.append("|---|---:|---:|---:|---:|---|")
for j in JUDGES:
    pairs = per_judge[j]
    if not pairs: continue
    d_ = [p["delta"] for p in pairs]
    b_ = [p["baseline"] for p in pairs]
    n = len(pairs)
    r_ = pearson(d_, b_); sp_ = spearman(d_, b_)
    lo, hi = boot_ci(d_, b_, spearman, B=B)
    cell = "—" if np.isnan(lo) else f"[{lo:.3f}, {hi:.3f}]"
    md.append(f"| {SHORT[j]} | {n} | {np.mean(d_):+.3f} | {r_:+.3f} | {sp_:+.3f} | {cell} |")

md.append("\n## Per-quintile uplift\n")
md.append("Quintile by ascending baseline (Q1 lowest), n≈2 per quintile per judge:\n")
md.append("| Judge | Q1 | Q2 | Q3 | Q4 | Q5 |")
md.append("|---|---:|---:|---:|---:|---:|")
for j in JUDGES:
    pairs = per_judge[j]
    if not pairs: continue
    sp = sorted(pairs, key=lambda x: x["baseline"])
    n = len(sp)
    q_size = n // 5
    qm = []
    for k in range(5):
        chunk = sp[k*q_size:(k+1)*q_size]
        qm.append(float(np.mean([p["delta"] for p in chunk])) if chunk else float("nan"))
    md.append(f"| {SHORT[j]} | {qm[0]:+.3f} | {qm[1]:+.3f} | {qm[2]:+.3f} | {qm[3]:+.3f} | {qm[4]:+.3f} |")

md.append("\n## Interpretation\n")
md.append(
    "**Different baseline from the headline C1 self-preference.** The per-judge mean Δ in this table is "
    "not the same as the abstract's within-judge self-preference gap. Here Δ compares a judge's rating of "
    "its own authored response to the other three judges' consensus for that same response. By this "
    "between-judge baseline, all four judges rate their own outputs slightly above peer consensus, including "
    "Kimi (+0.56), even though Kimi's within-judge C1 self-gap is strongly negative.\n\n"
    "The floor-raising pattern is only suggestive in C1 because each judge has n=10 own-authored prompts. "
    "Claude and GPT have negative point estimates similar in sign to the causal label-swap mechanism, Gemini "
    "is near null, and Kimi is negative but very uncertain. The native label-swap experiment remains the "
    "cleaner causal test of displayed-label effects."
)
(OUT / "floor_raising_c1_observational.md").write_text("\n".join(md) + "\n")
print("Wrote", csv_p)
print("Wrote", OUT / "floor_raising_c1_observational.md")
