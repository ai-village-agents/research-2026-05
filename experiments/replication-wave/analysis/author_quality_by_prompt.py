#!/usr/bin/env python3
"""Prompt-level C1 author-quality diagnostics using non-self judgments only.

The aggregate author-quality diagnostic shows Kimi-authored C1 originals score
far below the other three authors when judged by non-self judges. This script
asks whether that gap is concentrated in a few prompts or broad across the OOD
prompt suite.
"""
from __future__ import annotations

import csv
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
LONG = RESULTS / "long_scores.csv"
DIMS = ["correctness", "completeness", "clarity", "creativity", "constraint_adherence"]
AUTHORS = ["claude-opus-4.7", "gemini-3.1-pro", "gpt-5.5", "kimi-k2.6"]
NON_KIMI = [a for a in AUTHORS if a != "kimi-k2.6"]


def composite(row: dict[str, str]) -> float:
    return sum(float(row[d]) for d in DIMS) / len(DIMS)


def main() -> None:
    rows: list[dict[str, str]] = []
    with LONG.open(newline="") as f:
        for row in csv.DictReader(f):
            if row["condition"] == "c1" and row["judge"] != row["author"]:
                rows.append(row)
    if len(rows) != 120:
        raise SystemExit(f"expected 120 non-self C1 rows, found {len(rows)}")

    by_prompt_author: dict[tuple[str, str], list[float]] = defaultdict(list)
    by_prompt_non_kimi: dict[str, list[float]] = defaultdict(list)
    for row in rows:
        c = composite(row)
        by_prompt_author[(row["prompt_id"], row["author"] )].append(c)
        if row["author"] != "kimi-k2.6":
            by_prompt_non_kimi[row["prompt_id"]].append(c)

    prompt_ids = sorted({row["prompt_id"] for row in rows})

    means_path = RESULTS / "author_quality_nonself_c1_by_prompt.csv"
    with means_path.open("w", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["prompt_id", "author", "mean", "sd", "n"])
        for prompt_id in prompt_ids:
            for author in AUTHORS:
                vals = by_prompt_author[(prompt_id, author)]
                if len(vals) != 3:
                    raise SystemExit(f"expected 3 non-self scores for {prompt_id}/{author}, found {len(vals)}")
                w.writerow([
                    prompt_id,
                    author,
                    f"{statistics.mean(vals):.6f}",
                    f"{statistics.stdev(vals):.6f}",
                    len(vals),
                ])

    gaps: list[tuple[str, float, float, float]] = []
    gap_path = RESULTS / "author_quality_kimi_gap_by_prompt.csv"
    with gap_path.open("w", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["prompt_id", "kimi_mean", "non_kimi_mean", "kimi_minus_non_kimi"])
        for prompt_id in prompt_ids:
            kimi_mean = statistics.mean(by_prompt_author[(prompt_id, "kimi-k2.6")])
            non_kimi_mean = statistics.mean(by_prompt_non_kimi[prompt_id])
            gap = kimi_mean - non_kimi_mean
            gaps.append((prompt_id, kimi_mean, non_kimi_mean, gap))
            w.writerow([prompt_id, f"{kimi_mean:.6f}", f"{non_kimi_mean:.6f}", f"{gap:.6f}"])

    lower = sum(gap < 0 for _, _, _, gap in gaps)
    mean_gap = statistics.mean(gap for _, _, _, gap in gaps)
    min_prompt, min_kimi, min_non, min_gap = min(gaps, key=lambda x: x[3])
    max_prompt, max_kimi, max_non, max_gap = max(gaps, key=lambda x: x[3])

    lines = [
        "# Prompt-level non-self C1 author-quality diagnostic",
        "",
        "Generated by `analysis/author_quality_by_prompt.py`. Uses only C1 rows where `judge != author`, so it excludes the self-judgment rows whose bias is under study.",
        "",
        "## Summary",
        "",
        f"- Non-self C1 rows: {len(rows)} (10 prompts × 4 authors × 3 non-self judges).",
        f"- Kimi-authored originals score below the non-Kimi author mean on **{lower}/{len(gaps)} prompts**.",
        f"- Mean prompt-level Kimi minus non-Kimi gap: **{mean_gap:+.3f}** composite points.",
        f"- Largest Kimi deficit: `{min_prompt}` (**{min_gap:+.3f}**, Kimi {min_kimi:.3f} vs non-Kimi {min_non:.3f}).",
        f"- Largest/only Kimi advantage: `{max_prompt}` (**{max_gap:+.3f}**, Kimi {max_kimi:.3f} vs non-Kimi {max_non:.3f}).",
        "",
        "Interpretation: the author-quality confound behind Kimi's observational self-penalty is broad across the OOD prompt set, not a single-prompt artifact. The one exception is `repl-history-001`, where Kimi-authored output slightly exceeds the non-Kimi mean.",
        "",
        "## Prompt table",
        "",
        "| Prompt | Kimi mean | Non-Kimi mean | Kimi − non-Kimi |",
        "|---|---:|---:|---:|",
    ]
    for prompt_id, kimi_mean, non_kimi_mean, gap in gaps:
        lines.append(f"| `{prompt_id}` | {kimi_mean:.3f} | {non_kimi_mean:.3f} | {gap:+.3f} |")
    lines.extend([
        "",
        "Outputs:",
        "- `results/author_quality_nonself_c1_by_prompt.csv`: author means per prompt from three non-self judges.",
        "- `results/author_quality_kimi_gap_by_prompt.csv`: Kimi-vs-non-Kimi prompt-level gap table.",
    ])
    (RESULTS / "author_quality_by_prompt.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {means_path}")
    print(f"wrote {gap_path}")
    print(f"wrote {RESULTS / 'author_quality_by_prompt.md'}")


if __name__ == "__main__":
    main()
