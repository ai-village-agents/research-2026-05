#!/usr/bin/env python3
"""
Per-response paired SELF causal contrast (Day 408 sess 5 extension).

For each judge, restrict to responses that appear in both sessions with two
different displayed labels, exactly one of which is the judge's own label.
For each such response, compute delta = composite(displayed=self) -
composite(displayed=other). Report the distribution: n, mean, median, sd,
fraction>0, sign-test p (exact binomial, 2-sided), and per-actual-author
breakdown.

This is distinct from the by-prompt and by-dim sign-tests already in the
results folder: it treats each *response* (10 prompts x 4 authors = up to
40 candidates per judge, of which ~half satisfy the self-shown criterion)
as a single paired observation, giving a clean response-level causal SELF
effect from the within-pair contrast.

Outputs:
- results/paired_self_response_level.csv
- results/paired_self_response_level.md
"""
from __future__ import annotations
import csv, hashlib, json
from collections import defaultdict
from pathlib import Path
from math import comb

ROOT = Path(__file__).resolve().parents[1]
PACKETS = ROOT / "data" / "label_swap_packets"
SCORES = ROOT / "score_sheets" / "label_swap"
ALT_SCORES = ROOT / "data" / "label_swap_scores"
RESPONSES = ROOT / "responses"
RESULTS = ROOT / "results"
RESULTS.mkdir(parents=True, exist_ok=True)
DIMS = ["correctness","completeness","clarity","creativity","constraint_adherence"]
LABELS = ["claude-opus-4.7","gemini-3.1-pro","gpt-5.5","kimi-k2.6"]

def build_hash_to_author():
    """Build map from response_hash -> actual author by hashing C1 responses."""
    out = {}
    if not RESPONSES.exists(): return out
    for author_dir in RESPONSES.iterdir():
        if not author_dir.is_dir(): continue
        for f in author_dir.glob("*.json"):
            try:
                d = json.load(open(f))
            except Exception:
                continue
            txt = d.get("response") or d.get("response_text") or d.get("text")
            if not txt: continue
            h = hashlib.md5(txt.encode()).hexdigest()[:10]
            out[h] = author_dir.name
    return out

def score_file(judge, s):
    for c in (SCORES/judge/f"session_{s}_scored.json",
              ALT_SCORES/judge/f"session_{s}_scored.json"):
        if c.exists(): return c
    return None

def is_native(raw):
    if isinstance(raw, list): return True
    if isinstance(raw, dict): return raw.get("scoring_method")=="native_in_context"
    return False

def load_rows(judge, hash_to_author):
    meta = {}
    for s in (1,2):
        f = PACKETS/judge/f"session_{s}.json"
        if not f.exists(): continue
        for e in json.load(open(f))["entries"]:
            h = hashlib.md5(e["response_text"].encode()).hexdigest()[:10]
            meta[e["blind_id"]] = {
                "prompt_id": e["prompt_id"],
                "displayed_label": e["displayed_label"],
                "actual_author": e.get("actual_author") or hash_to_author.get(h),
                "response_hash": h,
            }
    rows = []
    for s in (1,2):
        f = score_file(judge, s)
        if f is None: continue
        raw = json.load(open(f))
        if not is_native(raw): continue
        entries = raw if isinstance(raw, list) else raw.get("entries", [])
        for e in entries:
            if not all(isinstance(e.get(d), (int,float)) for d in DIMS): continue
            m = meta.get(e["blind_id"])
            if not m: continue
            rows.append({
                "prompt_id": m["prompt_id"],
                "displayed_label": e.get("displayed_label", m["displayed_label"]),
                "actual_author": m.get("actual_author"),
                "response_hash": m["response_hash"],
                "composite": sum(e[d] for d in DIMS)/5.0,
            })
    return rows

def two_sided_binom_p(k, n):
    """Exact 2-sided binomial p, p0=0.5. Sum tail probs of |X-n/2|>=|k-n/2|."""
    if n == 0: return 1.0
    obs = abs(k - n/2)
    total = 2**n
    p = 0
    for i in range(n+1):
        if abs(i - n/2) >= obs - 1e-9:
            p += comb(n, i)
    return p / total

def main():
    hash_to_author = build_hash_to_author()
    csv_rows = []
    md_lines = [
        "# Per-response paired SELF causal contrast",
        "",
        "Generated by `analysis/paired_self_response_level.py`. For each judge,",
        "restricts to label-swap responses scored under both displayed labels where",
        "exactly one of the two labels is the judge's own. Reports the per-response",
        "paired delta = composite(displayed=SELF) − composite(displayed=OTHER), the",
        "fraction positive, exact 2-sided sign-test p, and a per-actual-author",
        "breakdown.",
        "",
        "This complements the by-prompt sign-test (pools all 4 labels per prompt)",
        "and by-dim breakdown (pools 5 rubric dims) already in §3.10.",
        "",
    ]

    summary = ["| Judge | n responses | mean Δ | median | sd | frac Δ>0 | sign-test p |",
               "|---|---:|---:|---:|---:|---:|---:|"]

    breakdown = ["| Judge | Actual author | n | mean Δ |",
                 "|---|---|---:|---:|"]

    for j in LABELS:
        rows = load_rows(j, hash_to_author)
        if not rows: continue
        by_hash = defaultdict(list)
        for r in rows: by_hash[r["response_hash"]].append(r)
        deltas = []  # list of (delta, actual_author, prompt_id, hash)
        for h, lst in by_hash.items():
            if len(lst) != 2: continue
            labs = [r["displayed_label"] for r in lst]
            if j not in labs: continue
            if labs[0] == labs[1]: continue
            self_row = next(r for r in lst if r["displayed_label"] == j)
            other_row = next(r for r in lst if r["displayed_label"] != j)
            delta = self_row["composite"] - other_row["composite"]
            deltas.append({
                "delta": delta,
                "actual_author": self_row["actual_author"],
                "prompt_id": self_row["prompt_id"],
                "hash": h,
                "other_label": other_row["displayed_label"],
            })
            csv_rows.append({
                "judge": j, "response_hash": h,
                "prompt_id": self_row["prompt_id"],
                "actual_author": self_row["actual_author"] or "",
                "other_label": other_row["displayed_label"],
                "self_composite": f"{self_row['composite']:.3f}",
                "other_composite": f"{other_row['composite']:.3f}",
                "delta": f"{delta:+.3f}",
            })
        if not deltas: continue
        ds = sorted(d["delta"] for d in deltas)
        n = len(ds)
        mean = sum(ds)/n
        med = ds[n//2] if n%2 else (ds[n//2-1]+ds[n//2])/2
        sd = (sum((x-mean)**2 for x in ds)/(n-1))**0.5 if n>1 else float('nan')
        pos = sum(1 for x in ds if x > 0)
        # tie-aware sign-test: drop zeros
        nonzero = [x for x in ds if x != 0]
        k = sum(1 for x in nonzero if x > 0)
        p = two_sided_binom_p(k, len(nonzero))
        summary.append(f"| {j} | {n} | {mean:+.3f} | {med:+.3f} | {sd:.3f} | {pos}/{n} | {p:.3f} |")

        # per-actual-author breakdown
        by_auth = defaultdict(list)
        for d in deltas:
            by_auth[d["actual_author"] or "unknown"].append(d["delta"])
        md_lines.append(f"### Judge: {j}")
        md_lines.append("")
        md_lines.append(f"- n responses with self-label shown: {n}")
        md_lines.append(f"- mean Δ = {mean:+.3f}, median = {med:+.3f}, sd = {sd:.3f}")
        md_lines.append(f"- Δ > 0 in {pos}/{n} responses (sign-test p = {p:.3f})")
        md_lines.append("")
        for a in sorted(by_auth):
            vals = by_auth[a]
            md_lines.append(f"  - actual_author={a}: n={len(vals)}, mean Δ = {sum(vals)/len(vals):+.3f}")
            breakdown.append(f"| {j} | {a} | {len(vals)} | {sum(vals)/len(vals):+.3f} |")
        md_lines.append("")

    md_lines.append("## Summary")
    md_lines.append("")
    md_lines.extend(summary)
    md_lines.append("")
    md_lines.append("## Per-actual-author breakdown")
    md_lines.append("")
    md_lines.extend(breakdown)
    md_lines.append("")
    md_lines.append("## Method")
    md_lines.append("")
    md_lines.append("Each judge scored 40 responses twice across sessions 1 and 2, rotating")
    md_lines.append("displayed labels via Latin square. For each response, we identify pairs")
    md_lines.append("where one of the two displayed labels is the judge's own. The per-response")
    md_lines.append("paired delta is composite(self-displayed) − composite(other-displayed). The")
    md_lines.append("sign-test is an exact 2-sided binomial under H₀: P(Δ>0)=0.5, dropping ties.")
    md_lines.append("")

    out_csv = RESULTS / "paired_self_response_level.csv"
    with open(out_csv, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["judge","response_hash","prompt_id","actual_author","other_label","self_composite","other_composite","delta"], lineterminator="\n")
        w.writeheader()
        for r in csv_rows: w.writerow(r)
    out_md = RESULTS / "paired_self_response_level.md"
    out_md.write_text("\n".join(md_lines))
    print(f"Wrote {out_csv}")
    print(f"Wrote {out_md}")

if __name__ == "__main__":
    main()
