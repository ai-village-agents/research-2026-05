#!/usr/bin/env python3
"""Per-dimension paired within-response label-swap residuals (D408 sess 4).

Same paired design as paired_label_swap_analysis.py, but instead of collapsing
to the 5-dim composite we report each of the 5 dimensions separately for each
(judge, displayed_label) cell. This tests whether the causal label effect is
broad (all 5 dims same direction) or concentrated on specific dimensions.

Outputs:
- experiments/replication-wave/results/paired_label_swap_by_dim.md
- experiments/replication-wave/results/paired_label_swap_by_dim.csv
"""
from __future__ import annotations

import csv
import hashlib
import json
import random
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKETS = ROOT / "data" / "label_swap_packets"
SCORES = ROOT / "score_sheets" / "label_swap"
ALT_SCORES = ROOT / "data" / "label_swap_scores"
RESULTS = ROOT / "results"
RESULTS.mkdir(parents=True, exist_ok=True)

DIMS = ["correctness", "completeness", "clarity", "creativity", "constraint_adherence"]
LABELS = ["claude-opus-4.7", "gemini-3.1-pro", "gpt-5.5", "kimi-k2.6"]


def load_packet_meta(judge: str) -> dict[str, dict]:
    meta = {}
    for s in (1, 2):
        f = PACKETS / judge / f"session_{s}.json"
        if not f.exists():
            continue
        for e in json.load(open(f))["entries"]:
            meta[e["blind_id"]] = {
                "session": s,
                "prompt_id": e["prompt_id"],
                "displayed_label": e["displayed_label"],
                "response_hash": hashlib.md5(e["response_text"].encode()).hexdigest()[:10],
            }
    return meta


def score_file(judge: str, session: int) -> Path | None:
    """Return native scored-file path, preferring canonical score_sheets/.

    The canonical committed location is score_sheets/label_swap/<judge>/, but
    we also accept data/label_swap_scores/<judge>/ as a compatibility fallback
    because that path was mentioned in one handoff message.
    """
    candidates = [
        SCORES / judge / f"session_{session}_scored.json",
        ALT_SCORES / judge / f"session_{session}_scored.json",
    ]
    for candidate in candidates:
        if candidate.exists():
            return candidate
    return None


def is_native(raw) -> bool:
    if isinstance(raw, list):
        return True
    if isinstance(raw, dict):
        return raw.get("scoring_method") == "native_in_context"
    return False


def load_judge_rows(judge: str) -> list[dict]:
    meta = load_packet_meta(judge)
    rows = []
    for s in (1, 2):
        f = score_file(judge, s)
        if f is None:
            continue
        raw = json.load(open(f))
        if not is_native(raw):
            continue
        entries = raw if isinstance(raw, list) else raw.get("entries", [])
        for e in entries:
            if not all(isinstance(e.get(d), (int, float)) for d in DIMS):
                continue
            m = meta.get(e["blind_id"])
            if not m:
                continue
            row = {
                "judge": judge,
                "blind_id": e["blind_id"],
                "displayed_label": e.get("displayed_label", m["displayed_label"]),
                "response_hash": m["response_hash"],
            }
            for d in DIMS:
                row[d] = e[d]
            rows.append(row)
    return rows


def paired_residuals_per_dim(rows: list[dict]) -> dict[tuple[str, str], list[float]]:
    """Returns {(displayed_label, dim): [residual, ...]}"""
    by_resp = defaultdict(list)
    for r in rows:
        by_resp[r["response_hash"]].append(r)
    pairs = [v for v in by_resp.values() if len(v) == 2]
    residuals: dict[tuple[str, str], list[float]] = defaultdict(list)
    for pair in pairs:
        for d in DIMS:
            m = (pair[0][d] + pair[1][d]) / 2
            for p in pair:
                residuals[(p["displayed_label"], d)].append(p[d] - m)
    return residuals, pairs


def bootstrap_ci(values: list[float], B: int = 2000, seed: int = 42) -> tuple[float, float]:
    if not values:
        return (float("nan"), float("nan"))
    rng = random.Random(seed)
    means = []
    n = len(values)
    for _ in range(B):
        s = sum(values[rng.randrange(n)] for _ in range(n)) / n
        means.append(s)
    means.sort()
    return (means[int(0.025 * B)], means[int(0.975 * B)])


def main():
    out_md = RESULTS / "paired_label_swap_by_dim.md"
    out_csv = RESULTS / "paired_label_swap_by_dim.csv"

    lines = [
        "# Per-dimension paired within-response label-swap residuals",
        "",
        "Generated by `analysis/paired_label_swap_by_dim.py`. For each (judge, displayed",
        "label) cell, each of 5 rubric dimensions is residualized against the paired",
        "within-response mean before averaging. Tests whether the causal label effect is",
        "broadly distributed across dimensions or concentrated on one or two.",
        "",
        f"Dimensions: {', '.join(DIMS)}",
        "",
    ]
    csv_rows = [("judge", "displayed_label", "dim", "n", "residual_mean", "ci_lo", "ci_hi")]

    for j in LABELS:
        rows = load_judge_rows(j)
        if not rows:
            continue
        residuals, pairs = paired_residuals_per_dim(rows)
        if not pairs:
            continue
        lines.append(f"## Judge: {j}  ({len(pairs)} paired responses)")
        lines.append("")
        lines.append("| Displayed label | " + " | ".join(DIMS) + " |")
        lines.append("|---|" + "---:|" * len(DIMS))
        for lab in LABELS:
            cells = []
            for d in DIMS:
                vals = residuals.get((lab, d), [])
                if not vals:
                    cells.append("—")
                    continue
                mean = sum(vals) / len(vals)
                lo, hi = bootstrap_ci(vals)
                cells.append(f"{mean:+.3f}")
                csv_rows.append((j, lab, d, len(vals), f"{mean:+.3f}", f"{lo:+.3f}", f"{hi:+.3f}"))
            if any(c != "—" for c in cells):
                lines.append(f"| {lab} | " + " | ".join(cells) + " |")
        lines.append("")
        # SELF row with CIs
        lines.append(f"### Self-label ({j}) per-dim residuals with bootstrap 95% CI")
        for d in DIMS:
            vals = residuals.get((j, d), [])
            if not vals:
                continue
            mean = sum(vals) / len(vals)
            lo, hi = bootstrap_ci(vals)
            sd = statistics.stdev(vals) if len(vals) > 1 else float("nan")
            lines.append(f"- {d}: {mean:+.3f}  n={len(vals)} sd={sd:.3f} CI=[{lo:+.3f}, {hi:+.3f}]")
        lines.append("")

    with open(out_md, "w") as f:
        f.write("\n".join(lines))
    with open(out_csv, "w", newline="") as f:
        csv.writer(f).writerows(csv_rows)
    print(f"Wrote {out_md} and {out_csv}")


if __name__ == "__main__":
    main()
