#!/usr/bin/env python3
"""Cross-judge concordance of response-level SELF-label deltas.

Uses results/paired_self_response_level.csv from the native label-swap slice.
Each row is a response where one displayed label was the judge's own and the
other was a non-self label, with delta = composite(self label) - composite(other
label). Because the Latin-square S1+S2 slice gives each response to only two of
three currently completed native judges under a self/non-self contrast, this is
an overlap diagnostic rather than a primary estimator.
"""
from __future__ import annotations

import csv
import math
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
RESULTS = ROOT / "experiments" / "replication-wave" / "results"
IN = RESULTS / "paired_self_response_level.csv"
OUT_CSV = RESULTS / "cross_judge_response_level.csv"
OUT_MD = RESULTS / "cross_judge_response_level.md"


def read_rows() -> list[dict[str, str]]:
    with IN.open(newline="") as f:
        return list(csv.DictReader(f))


def pearson(xs: list[float], ys: list[float]) -> float | None:
    if len(xs) < 2:
        return None
    mx, my = sum(xs) / len(xs), sum(ys) / len(ys)
    vx = sum((x - mx) ** 2 for x in xs)
    vy = sum((y - my) ** 2 for y in ys)
    if vx == 0 or vy == 0:
        return None
    return sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / math.sqrt(vx * vy)


def sign(v: float) -> int:
    return 1 if v > 0 else -1 if v < 0 else 0


def fmt_float(x: float | None, digits: int = 3) -> str:
    if x is None:
        return "NA"
    return f"{x:+.{digits}f}"


def main() -> None:
    rows = read_rows()
    by_response: dict[str, list[dict[str, str]]] = defaultdict(list)
    for r in rows:
        by_response[r["response_hash"]].append(r)

    pair_rows: list[dict[str, str]] = []
    for response_hash, rs in sorted(by_response.items()):
        if len(rs) < 2:
            continue
        rs = sorted(rs, key=lambda r: r["judge"])
        for i in range(len(rs)):
            for j in range(i + 1, len(rs)):
                a, b = rs[i], rs[j]
                da, db = float(a["delta"]), float(b["delta"])
                pair_rows.append({
                    "judge_a": a["judge"],
                    "judge_b": b["judge"],
                    "response_hash": response_hash,
                    "prompt_id": a["prompt_id"],
                    "actual_author": a["actual_author"],
                    "delta_a": f"{da:+.3f}",
                    "delta_b": f"{db:+.3f}",
                    "same_sign_nonzero": str(sign(da) == sign(db) and sign(da) != 0).lower(),
                    "opposite_sign_nonzero": str(sign(da) == -sign(db) and sign(da) != 0).lower(),
                    "any_tie": str(sign(da) == 0 or sign(db) == 0).lower(),
                })

    with OUT_CSV.open("w", newline="") as f:
        fieldnames = ["judge_a", "judge_b", "response_hash", "prompt_id", "actual_author", "delta_a", "delta_b", "same_sign_nonzero", "opposite_sign_nonzero", "any_tie"]
        w = csv.DictWriter(f, fieldnames=fieldnames, lineterminator="\n")
        w.writeheader()
        w.writerows(pair_rows)

    by_pair: dict[tuple[str, str], list[dict[str, str]]] = defaultdict(list)
    for r in pair_rows:
        by_pair[(r["judge_a"], r["judge_b"])].append(r)

    lines: list[str] = []
    lines.append("# Cross-judge concordance of response-level SELF-label deltas")
    lines.append("")
    lines.append("Generated by `analysis/cross_judge_response_level.py` from `paired_self_response_level.csv`. This is an exploratory overlap diagnostic: in the current three-judge native S1+S2 slice, each response has a response-level SELF-vs-OTHER delta for one or two judges, never all three. Pairwise overlap is therefore small and partly determined by the Latin-square label schedule.")
    lines.append("")
    lines.append("## Pairwise overlap summary")
    lines.append("")
    lines.append("| Judge A | Judge B | shared responses | Pearson r | same-sign nonzero | opposite-sign nonzero | ties involving either judge |")
    lines.append("|---|---|---:|---:|---:|---:|---:|")
    for (a, b), prs in sorted(by_pair.items()):
        xs = [float(r["delta_a"]) for r in prs]
        ys = [float(r["delta_b"]) for r in prs]
        same = sum(r["same_sign_nonzero"] == "true" for r in prs)
        opp = sum(r["opposite_sign_nonzero"] == "true" for r in prs)
        ties = sum(r["any_tie"] == "true" for r in prs)
        lines.append(f"| {a} | {b} | {len(prs)} | {fmt_float(pearson(xs, ys))} | {same} | {opp} | {ties} |")
    lines.append("")
    lines.append("## Reading")
    lines.append("")
    lines.append("- Claude and Gemini share five response-level SELF contrasts in this reduced slice. Their deltas are positively correlated in this tiny overlap, but the sample is too small for inference.")
    lines.append("- Any pair involving GPT-5.5 has undefined Pearson correlation because GPT's response-level deltas are all exactly zero in the native paired slice. This reinforces the earlier label-invariance/content-determinism caveat rather than estimating agreement.")
    lines.append("- In this small overlap slice, there is no strong evidence that response-level self-label uplift is a common response property shared across judges; the clearest signal remains Gemini-specific. Kimi's pending native rows could change both overlap and interpretation.")
    lines.append("")
    lines.append("## Shared-response rows")
    lines.append("")
    lines.append("| Judge A | Judge B | prompt | actual author | ΔA | ΔB | sign relation |")
    lines.append("|---|---|---|---|---:|---:|---|")
    for r in pair_rows:
        if r["same_sign_nonzero"] == "true":
            rel = "same nonzero"
        elif r["opposite_sign_nonzero"] == "true":
            rel = "opposite nonzero"
        else:
            rel = "tie involved"
        lines.append(f"| {r['judge_a']} | {r['judge_b']} | {r['prompt_id']} | {r['actual_author']} | {r['delta_a']} | {r['delta_b']} | {rel} |")
    lines.append("")
    OUT_MD.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT_CSV.relative_to(ROOT)}")
    print(f"wrote {OUT_MD.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
